import os
import torch

# Inspect POS tags, word IDs, and BERT embeddings for a selected sentence and layer

os.environ["CUDA_VISIBLE_DEVICES"] = "3"
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
print(f"Using device: {device}")

TARGET_LAYER = 2
SPLIT = "train"
SENTENCE = 0

from pathlib import Path

PROJECT_DIR = Path(__file__).resolve().parent.parent
file_path = PROJECT_DIR / "target_layers" / f"layer_{TARGET_LAYER}" / f"{SPLIT}_sentence_{SENTENCE}.pt"
data = torch.load(file_path, weights_only=False)

print(f"\n --- OPENING FILE: {file_path} --- \n")

print("\n1. POS tags:")
print(data['pos_tags'])
print(f"-> Total words: {len(data['pos_tags'])}")

print("\n2. Word IDs:")
print(data['word_ids'])
print(f"-> Total sub-tokens generated by BERT: {len(data['word_ids'])}")

print("\n3. BERT tensor dimensions:")
print("(batch_size, number_of_sub_token, embedding_dimension)")
print(data['hidden_states'].shape)

print("\n4. Actual Embeddings (Tensor values):")
print(data['hidden_states'])